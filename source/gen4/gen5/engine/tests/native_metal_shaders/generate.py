#!/usr/bin/env python3
"""Regenerate validated, readable SPIR-V fixtures; requires glslang and SPIRV-Tools."""
import pathlib
import subprocess
import tempfile

root = pathlib.Path(__file__).resolve().parent
variants = [
    ("Vertex", "vert", []), ("CullVertex", "vert", ["CULL"]),
    ("Control3", "tesc", ["CONTROL_POINTS=3"]),
    ("Control4", "tesc", ["CONTROL_POINTS=4"]),
    ("TriangleEvaluation", "tese", []),
    ("OddEvaluation", "tese", ["FRACTIONAL_ODD"]),
    ("EvenEvaluation", "tese", ["FRACTIONAL_EVEN"]),
    ("QuadEvaluation", "tese", ["QUADS"]),
    ("CullEvaluation", "tese", ["CULL"]),
    ("Fragment", "frag", []),
]
lines = ["// Generated by native_metal_shaders/generate.py from the adjacent GLSL sources.",
         "namespace PrimitiveContractSpv {"]
with tempfile.TemporaryDirectory(prefix="lumen-primitive-shaders-") as directory:
    for name, stage, definitions in variants:
        binary = pathlib.Path(directory) / (name + ".spv")
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.2", "-g0",
                        *["-D" + value for value in definitions],
                        "-o", str(binary), str(root / ("primitive." + stage))], check=True)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.2", str(binary)], check=True)
        assembly = subprocess.check_output(["spirv-dis", "--no-header", str(binary)], text=True)
        lines.extend([f'inline constexpr const char *{name} = R"SPV(', assembly, ')SPV";'])
lines.append("} // namespace PrimitiveContractSpv")
(root.parent / "NativeMetalPrimitiveShaders.inc").write_text("\n".join(lines) + "\n")
